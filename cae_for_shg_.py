def robust_minmax_nonzero(arr: np.ndarray, lo: int = 1, hi: int = 99):
    """
    Clip values based on `lo` and `hi` percentiles (default 1st and 99th),
    then normalize to [0,1]. Ignores zero pixels when calculating percentiles.
    """
    assert 0 <= lo < hi <= 100
    assert arr.ndim == 2 # (H,W)

    arr = arr.astype(np.float32)

    # only consider non-zero pixels for robust statistics
    nonzero_pixels = arr[arr > 0]
    if nonzero_pixels.size == 0:
        return np.zeros_like(arr)

    low_val  = np.percentile(nonzero_pixels, lo)
    high_val = np.percentile(nonzero_pixels, hi)

    # clip and normalize to [0,1]
    arr = np.clip(arr, low_val, high_val)
    if high_val > low_val: # avoid division by zero
        arr = (arr - low_val) / (high_val - low_val)
    else:
        # if all nonzero pixels are the same, they become 0.5 (or 0 if low_val=0)
        # set to 0 if low_val=0, else to 0.5 for uniform intensity
        arr = np.where(arr > 0, 0.5, 0.0)

    return arr

