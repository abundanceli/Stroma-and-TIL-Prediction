def find_existing_image(dir_path: Path, name_candidates):
    """
    dir_path: Path to folder
    name_candidates: list of strings (filenames, no directory)
    Returns Path or None.
    """
    for nm in name_candidates:
        p = dir_path / nm
        if p.exists():
            return p
    return None

