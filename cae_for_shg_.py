def train_smallae(
    model,
    train_loader,
    val_loader,
    ae_loss_fn,
    optimizer,
    scheduler,
    device,
    n_epochs=60,
    lambda_z=0.0,
    grad_clip=1.0,
    use_amp=True,
    early_stop_patience=15,
    ckpt_dir="checkpoints",
    best_name="best_small_ae.pt",
    last_name="last_small_ae.pt",
    recon_save_fn=None,
    viz_batch=None,
):
    os.makedirs(ckpt_dir, exist_ok=True)
    best_path = os.path.join(ckpt_dir, best_name)
    last_path = os.path.join(ckpt_dir, last_name)

    use_cuda_amp = bool(use_amp and device == "cuda")
    scaler = GradScaler(enabled=use_cuda_amp)

    best_val = float("inf")
    bad_epochs = 0

    for epoch in range(1, n_epochs + 1):
        # ---------------- TRAIN ----------------
        model.train()
        train_loss = train_recon = train_zreg = 0.0
        n_train = 0

        for x, *_ in train_loader:
            x = x.to(device, non_blocking=True)
            bs = x.size(0)

            optimizer.zero_grad(set_to_none=True)

            with autocast(device_type="cuda", enabled=use_cuda_amp):
                x_recon, z = model(x)
                loss, recon, zreg = ae_loss_fn(x, x_recon, z=z, lambda_z=lambda_z)

            scaler.scale(loss).backward()

            if grad_clip and grad_clip > 0:
                scaler.unscale_(optimizer)
                nn.utils.clip_grad_norm_(model.parameters(), grad_clip)

            scaler.step(optimizer)
            scaler.update()

            train_loss  += float(loss.detach()) * bs
            train_recon += float(recon.detach()) * bs
            train_zreg  += float(zreg.detach()) * bs
            n_train += bs

        train_loss  /= max(n_train, 1)
        train_recon /= max(n_train, 1)
        train_zreg  /= max(n_train, 1)

        # ---------------- VAL ----------------
        model.eval()
        val_loss = val_recon = val_zreg = 0.0
        n_val = 0

        with torch.no_grad():
            for x, *_ in val_loader:
                x = x.to(device, non_blocking=True)
                bs = x.size(0)

                with autocast(device_type="cuda", enabled=use_cuda_amp):
                    x_recon, z = model(x)
                    loss, recon, zreg = ae_loss_fn(x, x_recon, z=z, lambda_z=lambda_z)

                val_loss  += float(loss) * bs
                val_recon += float(recon) * bs
                val_zreg  += float(zreg) * bs
                n_val += bs

        val_loss  /= max(n_val, 1)
        val_recon /= max(n_val, 1)
        val_zreg  /= max(n_val, 1)

        if scheduler is not None:
            scheduler.step(val_loss)

        lr_now = optimizer.param_groups[0]["lr"]

        print(
            f"[Epoch {epoch:03d}] "
            f"Train: L={train_loss:.4f} (Recon={train_recon:.4f}, Zreg={train_zreg:.4f}) | "
            f"Val:   L={val_loss:.4f} (Recon={val_recon:.4f}, Zreg={val_zreg:.4f}) | "
            f"LR={lr_now:.2e}"
        )

        # save LAST
        torch.save({
            "epoch": epoch,
            "model_state": model.state_dict(),
            "optimizer_state": optimizer.state_dict(),
            "val_loss": val_loss,
        }, last_path)

        # save BEST + early stopping
        improved = val_loss < (best_val - 1e-4)
        if improved:
            best_val = val_loss
            bad_epochs = 0
            torch.save({
                "epoch": epoch,
                "model_state": model.state_dict(),
                "optimizer_state": optimizer.state_dict(),
                "val_loss": val_loss,
            }, best_path)
            print(f"  ✅ Saved BEST (val={val_loss:.5f})")
        else:
            bad_epochs += 1

        # optional recon visualization
        # optional recon visualization
        do_viz = (recon_save_fn is not None) and (viz_batch is not None) and (epoch == 1 or epoch % RECON_EVERY == 0)

        if do_viz:
            model.eval()
            try:
                with torch.no_grad():
                    with autocast(device_type="cuda", enabled=use_cuda_amp):
                        x_recon, _ = model(viz_batch)   # viz_batch already on DEVICE
                recon_save_fn(epoch, viz_batch, x_recon)
                print(f"✅ Saved recon at epoch {epoch} -> {OUT_DIR_RECONS}")
            except Exception as e:
                print(f"⚠️ Recon save failed at epoch {epoch}: {repr(e)}")
            finally:
                model.train()

        if bad_epochs >= early_stop_patience:
            print(f"🛑 Early stopping at epoch {epoch} (no improvement for {early_stop_patience} epochs).")
            break

    print(f"Best val loss: {best_val:.5f}")
    print(f"Best checkpoint: {best_path}")
    print(f"Last checkpoint: {last_path}")
    return best_path, last_path

