def read_he_field(path: Path):
    img = cv2.imread(str(path), cv2.IMREAD_COLOR)
    if img is None:
        raise FileNotFoundError(f"Could not read HE image {path}")
    return img   # BGR; we'll convert to RGB later in dataset if needed


def read_shg_field(path: Path):
    img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise FileNotFoundError(f"Could not read SHG image {path}")
    img = img.astype(np.float32)
    # normalize per field to [0,1] then [0,255]
    img -= img.min()
    if img.max() > 0:
        img /= img.max()
    img = (img * 255.0).clip(0, 255).astype(np.uint8)
    return img


def read_tilden_field(path: Path):
    img = tiff.imread(str(path)).astype(np.float32)
    # normalize per field to [0,1]
    img -= img.min()
    if img.max() > 0:
        img /= img.max()
    return img  # float [0,1]

