class SHGCAEDataset(Dataset):
    """
    CAE dataset: returns SHG tile in [0,1] (robust per-tile norm),
    plus a TIL scalar and meta for later analysis.
    """
    def __init__(self, samples, augment=False, lo=1, hi=99, til_transform="sqrt"):
        self.samples = samples
        self.augment = augment
        self.lo = lo
        self.hi = hi
        self.til_transform = til_transform

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        sample = self.samples[idx]
        shg_path = sample["shg"]
        til_path = sample["til_den"]

        patient_code = sample.get("patient", "")
        field_id     = sample.get("field_id", "")
        patch_name   = sample.get("name", "")

        # --- load SHG as float in [0,1] ---
        shg = cv2.imread(str(shg_path), cv2.IMREAD_GRAYSCALE)
        if shg is None:
            raise FileNotFoundError(f"Failed to read SHG: {shg_path}")
        shg = shg.astype(np.float32) / 255.0

        # robust per-tile normalize to [0,1]
        shg = robust_minmax_nonzero(shg, lo=self.lo, hi=self.hi)

        # --- load TIL map -> scalar target ---
        til = cv2.imread(str(til_path), cv2.IMREAD_GRAYSCALE)
        if til is None:
            raise FileNotFoundError(f"Failed to read TIL: {til_path}")
        til = til.astype(np.float32)
        if til.max() > 1.0:
            til /= 255.0

        til_mean = float(til.mean())
        if self.til_transform == "sqrt":
            til_target = np.sqrt(til_mean)
        elif self.til_transform == "raw":
            til_target = til_mean
        else:
            raise ValueError(f"Unknown til_transform: {self.til_transform}")

        # --- augmentation (apply to numpy BEFORE tensor) ---
        if self.augment:
            # If your augment function expects both, pass both and keep them aligned
            shg, til = augment_shg_til(shg, til)
            # (optional) recompute scalar after aug if til changes:
            til_mean = float(til.mean())
            til_target = np.sqrt(til_mean) if self.til_transform == "sqrt" else til_mean

        shg = np.ascontiguousarray(shg)   # or shg = shg.copy()
        x = torch.from_numpy(shg).unsqueeze(0).float()  # (1,H,W) in [0,1]
        y_til = torch.tensor(til_target, dtype=torch.float32)

        meta = {
            "patient": patient_code,
            "field_id": field_id,
            "patch_id": patch_name,
            "shg_path": str(shg_path),
            "til_path": str(til_path),
        }

        return x, y_til, meta


