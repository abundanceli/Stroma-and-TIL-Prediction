def augment_shg_til(shg, til, brightness_jitter=True):
    """
    shg, til: numpy arrays in [0,1], shape (H,W)
    Apply same spatial transforms to both; brightness jitter to SHG only.
    """
    # Random horizontal flip
    if random.random() < 0.5:
        shg = np.fliplr(shg)
        til = np.fliplr(til)

    # Random vertical flip
    if random.random() < 0.5:
        shg = np.flipud(shg)
        til = np.flipud(til)

    # Random 0/90/180/270 rotation
    k = random.randint(0, 3)
    if k > 0:
        shg = np.rot90(shg, k)
        til = np.rot90(til, k)

    # Small brightness jitter on SHG ONLY
    if brightness_jitter and random.random() < 0.3:
        factor = random.uniform(0.9, 1.1)
        shg = np.clip(shg * factor, 0.0, 1.0)

    return shg, til

