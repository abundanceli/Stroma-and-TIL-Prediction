def tile_one_patient(patient_code: str):
    patient_dir = PATIENT_ROOT / patient_code / "patches_20x"
    he_dir      = patient_dir / "HE"
    shg_dir     = patient_dir / "SHG"
    til_dir     = patient_dir / "TIL"

    if not he_dir.exists() or not shg_dir.exists() or not til_dir.exists():
        print(f"[WARN] Missing HE/SHG/TIL folder(s) for {patient_code}, skipping.")
        return []

    out_he_dir   = OUTPUT_ROOT / patient_code / "HE"
    out_shg_dir  = OUTPUT_ROOT / patient_code / "SHG"
    out_til_dir  = OUTPUT_ROOT / patient_code / "TIL_DEN"
    out_he_dir.mkdir(parents=True, exist_ok=True)
    out_shg_dir.mkdir(parents=True, exist_ok=True)
    out_til_dir.mkdir(parents=True, exist_ok=True)

    til_den_fields = sorted(til_dir.glob("*_til_den.tif"))
    print(f"[{patient_code}] Found {len(til_den_fields)} TIL_DEN fields.")

    samples = []
    n_fields_used = 0
    n_patches_total = 0

    for t_path in til_den_fields:
        stem = t_path.stem   # e.g. "patch_0003_til_den"

        if stem.endswith("_til_den"):
            field_id = stem.replace("_til_den", "")   # "patch_0003"
        else:
            # fallback if the pattern ever changes
            parts = stem.split("_")
            field_id = "_".join(parts[:2])  # e.g. "patch_0003"

        # -------- robust HE filename search --------
        he_candidates = [
            f"{field_id}.png",
            f"{field_id}.tif",
            f"{field_id}.tiff",
            f"{field_id}.jpg",
            f"{field_id}.jpeg",
        ]
        he_path = find_existing_image(he_dir, he_candidates)

        # -------- robust SHG filename search --------
        shg_candidates = [
            f"shg_{field_id}.png",
            f"shg_{field_id}.tif",
            f"shg_{field_id}.tiff",
            f"{field_id}.png",
            f"{field_id}.tif",
            f"{field_id}.tiff",
        ]
        shg_path = find_existing_image(shg_dir, shg_candidates)

        if he_path is None or shg_path is None:
            print(f"[WARN] Missing HE/SHG for {field_id} in {patient_code}, skipping field.")
            continue

        try:
            he_img   = read_he_field(he_path)      # (H,W,3)
            shg_img  = read_shg_field(shg_path)    # (H,W)
            tden_img = read_tilden_field(t_path)   # (H,W) float [0,1]
        except Exception as e:
            print(f"[WARN] Could not read one or more images for {field_id} in {patient_code}: {e}")
            continue

        H, W, _ = he_img.shape
        if shg_img.shape != (H, W) or tden_img.shape != (H, W):
            print(f"[WARN] Shape mismatch for {field_id} in {patient_code}: "
                  f"HE {he_img.shape}, SHG {shg_img.shape}, TIL_DEN {tden_img.shape}, skipping field.")
            continue

        if H % PATCH_SIZE != 0 or W % PATCH_SIZE != 0:
            print(f"[WARN] Field {field_id} size {H}x{W} not divisible by {PATCH_SIZE}, skipping field.")
            continue

        n_fields_used += 1

        ny = H // PATCH_SIZE
        nx = W // PATCH_SIZE

        for iy in range(ny):
            for ix in range(nx):
                y0 = iy * PATCH_SIZE
                x0 = ix * PATCH_SIZE
                y1 = y0 + PATCH_SIZE
                x1 = x0 + PATCH_SIZE

                he_patch   = he_img[y0:y1, x0:x1, :]
                shg_patch  = shg_img[y0:y1, x0:x1]
                tden_patch = tden_img[y0:y1, x0:x1]   # float [0,1]

                tden_u8 = (tden_patch * 255.0).clip(0, 255).astype(np.uint8)

                tile_name = f"{patient_code}_{field_id}_y{y0}_x{x0}.png"

                out_he   = out_he_dir  / tile_name
                out_shg  = out_shg_dir / tile_name
                out_tden = out_til_dir / tile_name

                cv2.imwrite(str(out_he), he_patch)
                cv2.imwrite(str(out_shg), shg_patch)
                cv2.imwrite(str(out_tden), tden_u8)

                samples.append({
                    "patient": patient_code,
                    "field_id": field_id,
                    "name": tile_name,
                    "he": out_he,
                    "shg": out_shg,
                    "til_den": out_tden,
                })
                n_patches_total += 1

    print(f"[{patient_code}] Used {n_fields_used} fields, saved {n_patches_total} patches.")
    print("---------------------------------------------------------")
    return samples

