class ConvBlock(nn.Module):
    def __init__(self, in_ch, out_ch, p_drop=0):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, 3, padding=1),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_ch, out_ch, 3, padding=1),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
        )
        self.drop = nn.Dropout2d(p_drop)

    def forward(self, x):
        return self.drop(self.block(x))


class UpConv(nn.Module):
    def __init__(self, in_ch, out_ch):
        super().__init__()
        self.up   = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
        self.conv = nn.Conv2d(in_ch, out_ch, 3, padding=1)
        self.bn   = nn.BatchNorm2d(out_ch)
        self.relu = nn.ReLU(inplace=True)

    def forward(self, x):
        x = self.up(x)
        x = self.relu(self.bn(self.conv(x)))
        return x


class AttentionGate(nn.Module):
    def __init__(self, F_g, F_l, F_int):
        super().__init__()
        self.W_g = nn.Sequential(
            nn.Conv2d(F_g, F_int, kernel_size=1),
            nn.BatchNorm2d(F_int)
        )
        self.W_x = nn.Sequential(
            nn.Conv2d(F_l, F_int, kernel_size=1),
            nn.BatchNorm2d(F_int)
        )
        self.psi = nn.Sequential(
            nn.Conv2d(F_int, 1, kernel_size=1),
            nn.BatchNorm2d(1),
            nn.Sigmoid()
        )
        self.relu = nn.ReLU(inplace=True)

        # <--- this is new
        self.last_psi = None

    def forward(self, g, x):
        g1  = self.W_g(g)
        x1  = self.W_x(x)
        psi = self.relu(g1 + x1)
        psi = self.psi(psi)          # [B,1,h,w] in [0,1]
        self.last_psi = psi          # <--- store attention map
        return x * psi

class AttUNet(nn.Module):
    def __init__(self, img_ch=1, output_ch=1, base_ch=32, p_drop=0.2):
        super().__init__()
        c1, c2, c3, c4, c5 = base_ch, base_ch*2, base_ch*4, base_ch*8, base_ch*16

        # encoder
        self.conv1 = ConvBlock(img_ch, c1, p_drop=p_drop); self.pool1 = nn.MaxPool2d(2)
        self.conv2 = ConvBlock(c1, c2, p_drop=p_drop);     self.pool2 = nn.MaxPool2d(2)
        self.conv3 = ConvBlock(c2, c3, p_drop=p_drop);     self.pool3 = nn.MaxPool2d(2)
        self.conv4 = ConvBlock(c3, c4, p_drop=p_drop);     self.pool4 = nn.MaxPool2d(2)
        self.conv5 = ConvBlock(c4, c5, p_drop=p_drop)

        # decoder
        self.up5      = UpConv(c5, c4)
        self.att5     = AttentionBlock(c4, c4, c4//2)
        self.up_conv5 = ConvBlock(c5, c4, p_drop=p_drop)

        self.up4      = UpConv(c4, c3)
        self.att4     = AttentionBlock(c3, c3, c3//2)
        self.up_conv4 = ConvBlock(c4, c3, p_drop=p_drop)

        self.up3      = UpConv(c3, c2)
        self.att3     = AttentionBlock(c2, c2, c2//2)
        self.up_conv3 = ConvBlock(c3, c2, p_drop=p_drop)

        self.up2      = UpConv(c2, c1)
        self.att2     = AttentionBlock(c1, c1, c1//2)
        self.up_conv2 = ConvBlock(c2, c1, p_drop=p_drop)

        self.outc     = nn.Conv2d(c1, output_ch, 1)

    def forward(self, x):
        x1 = self.conv1(x); p1 = self.pool1(x1)
        x2 = self.conv2(p1); p2 = self.pool2(x2)
        x3 = self.conv3(p2); p3 = self.pool3(x3)
        x4 = self.conv4(p3); p4 = self.pool4(x4)
        x5 = self.conv5(p4)

        d5 = self.up5(x5); x4a = self.att5(d5, x4); d5 = self.up_conv5(torch.cat([x4a, d5], dim=1))
        d4 = self.up4(d5); x3a = self.att4(d4, x3); d4 = self.up_conv4(torch.cat([x3a, d4], dim=1))
        d3 = self.up3(d4); x2a = self.att3(d3, x2); d3 = self.up_conv3(torch.cat([x2a, d3], dim=1))
        d2 = self.up2(d3); x1a = self.att2(d2, x1); d2 = self.up_conv2(torch.cat([x1a, d2], dim=1))

        return self.outc(d2)


# ================== LOSS (continuous L1) ==================

class ContinuousL1Loss(nn.Module):
    """
    L1 between sigmoid(logits) and continuous TIL density [0,1].
    """
    def __init__(self):
        super().__init__()
        self.l1 = nn.L1Loss()

    def forward(self, logits, targets):
        probs = torch.sigmoid(logits)
        return self.l1(probs, targets)


# ================== METRICS ==================

def compute_pixel_metrics(pred_logits, true_cont, thr_cont=TIL_BIN_THR):
    """
    Compute AUROC & AUPRC by binarizing the continuous TIL map with thr_cont.
    """
    with torch.no_grad():
        probs = torch.sigmoid(pred_logits).view(-1).cpu().numpy().astype(np.float32)
        gt_bin = (true_cont.view(-1).cpu().numpy().astype(np.float32) >= thr_cont).astype(np.uint8)

        if gt_bin.sum() == 0 or gt_bin.sum() == len(gt_bin):
            return np.nan, np.nan

        auroc = roc_auc_score(gt_bin, probs)
        auprc = average_precision_score(gt_bin, probs)
        return float(auroc), float(auprc)


