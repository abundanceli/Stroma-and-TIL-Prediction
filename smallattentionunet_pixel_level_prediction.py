@torch.no_grad()
def evaluate_regression(model, loader, device):
    model.eval()

    # --- pixel-level stats ---
    all_true_pix = []
    all_pred_pix = []

    # --- patch-level stats (mean density per tile) ---
    patch_true = []
    patch_pred = []

    # --- patient-level stats ---
    patient_true_sum = defaultdict(float)
    patient_pred_sum = defaultdict(float)
    patient_npix      = defaultdict(int)

    for xb, yb, meta in loader:
        xb = xb.to(device, non_blocking=True)        # [B,C,H,W]
        yb = yb.to(device, non_blocking=True)        # [B,1,H,W], TIL_DEN in [0,1]

        logits = model(xb)
        probs  = torch.sigmoid(logits)               # [B,1,H,W] predicted density

        # pixel-level
        all_true_pix.append(yb.view(-1).cpu().numpy())
        all_pred_pix.append(probs.view(-1).cpu().numpy())

        # patch-level
        gt_mean   = yb.mean(dim=(1,2,3)).cpu().numpy()     # [B]
        pred_mean = probs.mean(dim=(1,2,3)).cpu().numpy()  # [B]
        patch_true.extend(gt_mean.tolist())
        patch_pred.extend(pred_mean.tolist())

        # patient-level aggregation
        if isinstance(meta, dict):
            patients_batch = meta["patient"]
        else:
            patients_batch = [m["patient"] for m in meta]

        B = xb.size(0)
        for i in range(B):
            pt  = str(patients_batch[i])
            gt_i   = yb[i,0].cpu().numpy()
            pred_i = probs[i,0].cpu().numpy()

            patient_true_sum[pt] += float(gt_i.sum())
            patient_pred_sum[pt] += float(pred_i.sum())
            patient_npix[pt]     += gt_i.size

    # concat pixel arrays
    all_true_pix = np.concatenate(all_true_pix)
    all_pred_pix = np.concatenate(all_pred_pix)

    # --- compute metrics ---

    def corr_pearson(y_true, y_pred):
        if len(y_true) < 2:
            return np.nan
        return float(np.corrcoef(y_true, y_pred)[0,1])

    # pixel-level
    pix_mae  = mean_absolute_error(all_true_pix, all_pred_pix)
    pix_rmse = np.sqrt(mean_squared_error(all_true_pix, all_pred_pix))
    pix_r2   = r2_score(all_true_pix, all_pred_pix)
    pix_r    = corr_pearson(all_true_pix, all_pred_pix)

    # patch-level
    patch_true_arr = np.array(patch_true)
    patch_pred_arr = np.array(patch_pred)
    patch_mae  = mean_absolute_error(patch_true_arr, patch_pred_arr)
    patch_rmse = np.sqrt(mean_squared_error(patch_true_arr, patch_pred_arr))
    patch_r2   = r2_score(patch_true_arr, patch_pred_arr)
    patch_r    = corr_pearson(patch_true_arr, patch_pred_arr)

    # patient-level (%TIL)
    patient_ids = sorted(patient_npix.keys())
    patient_true_pct = []
    patient_pred_pct = []
    for pt in patient_ids:
        total_pix = patient_npix[pt]
        t_sum = patient_true_sum[pt]
        p_sum = patient_pred_sum[pt]
        patient_true_pct.append(t_sum / max(1,total_pix))
        patient_pred_pct.append(p_sum / max(1,total_pix))

    patient_true_pct = np.array(patient_true_pct)
    patient_pred_pct = np.array(patient_pred_pct)

    pat_mae  = mean_absolute_error(patient_true_pct, patient_pred_pct)
    pat_rmse = np.sqrt(mean_squared_error(patient_true_pct, patient_pred_pct))
    pat_r2   = r2_score(patient_true_pct, patient_pred_pct)
    pat_r    = corr_pearson(patient_true_pct, patient_pred_pct)

    metrics = {
        "pixel":   {"MAE": pix_mae,  "RMSE": pix_rmse,  "R2": pix_r2,  "Pearson_r": pix_r},
        "patch":   {"MAE": patch_mae,"RMSE": patch_rmse,"R2": patch_r2,"Pearson_r": patch_r},
        "patient": {"MAE": pat_mae,  "RMSE": pat_rmse,  "R2": pat_r2,  "Pearson_r": pat_r},
        "patient_ids": patient_ids,
        "patient_true_pct": patient_true_pct,
        "patient_pred_pct": patient_pred_pct,
        "patch_true": patch_true_arr,
        "patch_pred": patch_pred_arr,
    }

    return metrics

