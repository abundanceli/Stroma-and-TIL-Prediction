def train_one_fold(fold_idx: int,
                   n_epochs: int = 30,
                   lr: float = 1e-4,
                   weight_decay: float = 1e-4,
                   save_dir: str = "./models"):
    os.makedirs(save_dir, exist_ok=True)

    train_loader, val_loader, test_loader, train_ds, val_ds, test_ds = \
        build_fold_loaders(fold_idx, batch_size=4, num_workers=0)

    in_ch = 4 if INPUT_MODALITY == "HE+SHG" else (3 if INPUT_MODALITY == "HE" else 1)

    model = AttnUNet(in_ch=in_ch, out_ch=1, base_ch=32, dropout_p=0.2).to(DEVICE)

    criterion = nn.BCEWithLogitsLoss()
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=weight_decay)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="min", factor=0.5, patience=4
    )

    best_val_loss = np.inf
    best_path = os.path.join(save_dir, f"best_model_fold{fold_idx}.pt")

    for epoch in range(1, n_epochs + 1):
        # ------ train ------
        model.train()
        running_loss = 0.0
        n_samples = 0

        pbar = tqdm(train_loader, desc=f"Fold {fold_idx} | Epoch {epoch} [train]", leave=False)
        for xb, yb, _ in pbar:
            xb = xb.to(DEVICE, non_blocking=True)
            yb = yb.to(DEVICE, non_blocking=True)

            optimizer.zero_grad()
            logits = model(xb)
            loss = criterion(logits, yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()

            bs = xb.size(0)
            running_loss += loss.item() * bs
            n_samples += bs
            pbar.set_postfix({"loss": running_loss / max(1, n_samples)})

        train_loss = running_loss / max(1, n_samples)

        # ------ validation ------
        model.eval()
        val_loss = 0.0
        n_val = 0
        with torch.no_grad():
            for xb, yb, _ in tqdm(val_loader,
                                  desc=f"Fold {fold_idx} | Epoch {epoch} [val]",
                                  leave=False):
                xb = xb.to(DEVICE, non_blocking=True)
                yb = yb.to(DEVICE, non_blocking=True)

                logits = model(xb)
                loss = criterion(logits, yb)

                bs = xb.size(0)
                val_loss += loss.item() * bs
                n_val += bs

        val_loss = val_loss / max(1, n_val)
        scheduler.step(val_loss)

        lr_now = optimizer.param_groups[0]["lr"]
        print(f"[Fold {fold_idx}] Epoch {epoch:03d} | "
              f"train_loss={train_loss:.4f}  val_loss={val_loss:.4f}  lr={lr_now:.2e}")

        # ------ save best ------
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save({
                "epoch": epoch,
                "model_state": model.state_dict(),
                "optimizer_state": optimizer.state_dict(),
                "val_loss": best_val_loss,
            }, best_path)
            print(f"  -> New best model saved to {best_path} (val_loss={best_val_loss:.4f})")

    print(f"Training finished for fold {fold_idx}. Best val_loss={best_val_loss:.4f}")
    return best_path

