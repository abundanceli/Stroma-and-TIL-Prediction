class TILDensityDataset(Dataset):
    """
    Dataset for patient-wise HE + SHG + TIL_DEN patches at 512x512.

    Layout:
      root/
        [patient_code]/
          HE/*.png
          SHG/*.png
          TIL_DEN/*.png

    We use TIL_DEN patches as labels; filenames are identical across modalities.
    """

    def __init__(self,
                 root: Path,
                 patients,
                 input_mod: str = "HE+SHG",
                 mask_mode: str = "density",
                 augment: bool = False):
        super().__init__()
        assert input_mod in ("HE", "SHG", "HE+SHG")
        assert mask_mode in ("binary", "density")

        self.root      = Path(root)
        self.patients  = list(patients)
        self.input_mod = input_mod
        self.mask_mode = mask_mode
        self.augment   = augment

        self.samples = []
        self.has_pos = []   # tile-level "any positive pixel" label

        for patient in self.patients:
            p_dir = self.root / patient
            he_dir  = p_dir / "HE"
            shg_dir = p_dir / "SHG"
            til_dir = p_dir / "TIL_DEN"

            if not til_dir.exists():
                print(f"  [WARN] No TIL_DEN folder for {patient}, skipping patient.")
                continue

            til_files = sorted(til_dir.glob("*.png"))
            print(f"[{patient}] Found {len(til_files)} TIL_DEN patches.")

            for t_path in til_files:
                fname = t_path.name

                he_path  = he_dir  / fname
                shg_path = shg_dir / fname

                ok = True
                if self.input_mod in ("HE", "HE+SHG") and not he_path.exists():
                    print(f"  [WARN] Missing HE for {patient}/{fname}, skipping.")
                    ok = False
                if self.input_mod in ("SHG", "HE+SHG") and not shg_path.exists():
                    print(f"  [WARN] Missing SHG for {patient}/{fname}, skipping.")
                    ok = False
                if not ok:
                    continue

                # compute has_pos once
                m_np = read_gray(t_path).astype(np.float32)
                pos_mask = (m_np > 0).astype(np.float32)
                has_pos = bool(pos_mask.sum() > 0)

                self.samples.append({
                    "patient": patient,
                    "name":    fname,
                    "he":      he_path if he_path.exists() else None,
                    "shg":     shg_path if shg_path.exists() else None,
                    "til":     t_path,
                })
                self.has_pos.append(has_pos)

        n_all = len(self.samples)
        n_pos = int(sum(self.has_pos))
        print(f"[DATASET] Loaded {n_all} tiles from {len(self.patients)} patients,"
              f" {n_pos} ({100.0*n_pos/max(1,n_all):.2f}%) tiles with TIL > 0.")

        # per-patient stats
        per_patient = defaultdict(lambda: [0, 0])  # [pos, total]
        for s, h in zip(self.samples, self.has_pos):
            pt = s["patient"]
            per_patient[pt][1] += 1
            if h:
                per_patient[pt][0] += 1
        print("  Per patient:")
        for pt in sorted(per_patient.keys()):
            pos, total = per_patient[pt]
            frac = 100.0 * pos / max(1, total)
            print(f"    {pt:20s} -> {pos:4d} / {total:4d} ({frac:6.2f}% positive)")

    def __len__(self):
        return len(self.samples)

    def _augment(self, x, y):
        # x: [C,H,W], y: [1,H,W]
        if random.random() < 0.5:
            x = torch.flip(x, dims=[2])
            y = torch.flip(y, dims=[2])
        if random.random() < 0.5:
            x = torch.flip(x, dims=[1])
            y = torch.flip(y, dims=[1])
        k = random.choice([0, 1, 2, 3])
        if k > 0:
            x = torch.rot90(x, k, dims=[1, 2])
            y = torch.rot90(y, k, dims=[1, 2])
        return x, y

    def __getitem__(self, idx):
        s = self.samples[idx]
        patient = s["patient"]
        name    = s["name"]

        # ---------- label (TIL_DEN) ----------
        mask_np = read_gray(s["til"]).astype(np.float32)

        if self.mask_mode == "binary":
            mask_np = (mask_np > 0).astype(np.float32)
        else:  # "density"
            mn, mx = mask_np.min(), mask_np.max()
            if mx > mn:
                mask_np = (mask_np - mn) / (mx - mn)
            else:
                mask_np = np.zeros_like(mask_np, dtype=np.float32)

        mask_t = torch.from_numpy(mask_np)[None, ...]  # [1,H,W]

        # ---------- inputs ----------
        if self.input_mod == "HE":
            he = read_rgb(s["he"]).astype(np.float32) / 255.0
            x_np = np.transpose(he, (2, 0, 1))  # [3,H,W]

        elif self.input_mod == "SHG":
            shg = read_gray(s["shg"]).astype(np.float32)
            mn, mx = shg.min(), shg.max()
            if mx > mn:
                shg = (shg - mn) / (mx - mn)
            else:
                shg = np.zeros_like(shg, dtype=np.float32)
            x_np = shg[None, ...]

        else:  # "HE+SHG"
            he = read_rgb(s["he"]).astype(np.float32) / 255.0
            he_chw = np.transpose(he, (2, 0, 1))  # [3,H,W]

            shg = read_gray(s["shg"]).astype(np.float32)
            mn, mx = shg.min(), shg.max()
            if mx > mn:
                shg = (shg - mn) / (mx - mn)
            else:
                shg = np.zeros_like(shg, dtype=np.float32)
            shg_ch = shg[None, ...]

            x_np = np.concatenate([he_chw, shg_ch], axis=0)  # [4,H,W]

        x_t = torch.from_numpy(x_np).float()

        if self.augment:
            x_t, mask_t = self._augment(x_t, mask_t)

        meta = {"patient": patient, "name": name}
        return x_t, mask_t, meta

# ================== PATIENT SPLITS (3 folds) (from 2wJeDMmEa8n9) ==================
def get_fold_splits(fold_idx: int):
    """
    3 folds, each with:
      a flexible number of train patients (total - 4)
      2 val patients
      2 test patients
    Patients are taken from PATIENT_CODES (sorted).
    """
    assert 0 <= fold_idx < 3

    # The original base calculation (3 * fold_idx) % N_PATIENTS works well
    # for rotating test and validation sets across folds for N_PATIENTS=8.
    base = (3 * fold_idx) % N_PATIENTS

    test_indices = [base % N_PATIENTS,
                    (base + 1) % N_PATIENTS]
    val_indices  = [(base + 2) % N_PATIENTS,
                    (base + 3) % N_PATIENTS]

    test_patients = [PATIENT_CODES[i] for i in test_indices]
    val_patients  = [PATIENT_CODES[i] for i in val_indices]

    test_set = set(test_patients)
    val_set  = set(val_patients)
    train_patients = [p for p in PATIENT_CODES
                      if p not in test_set and p not in val_set]

    # This assertion now correctly reflects the number of training patients given N_PATIENTS
    assert len(train_patients) == N_PATIENTS - 4, f"Expected {N_PATIENTS - 4} train patients, got {len(train_patients)}"
    assert len(val_patients) == 2
    assert len(test_patients) == 2

    print(f"\n===== Fold {fold_idx} =====")
    print("  Train patients:", train_patients)
    print("  Val patients:  ", val_patients)
    print("  Test patients: ", test_patients)

    return train_patients, val_patients, test_patients


