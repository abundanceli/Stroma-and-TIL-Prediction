class SHGOnlyTILDataset(Dataset):
    """
    SHG-only dataset:
    - SHG:    grayscale PNG, scaled to [0,1], brightness preserved.
    - TIL:    grayscale PNG in TIL_DEN, interpreted as continuous density
              and normalized by a global percentile scale.
    - Training target: continuous normalized TIL density map (no binarization).
    - Binary mask is used only for patch-level sampling & metrics.
    """
    def __init__(self,
                 data_root,
                 patient_list,
                 til_folder_name="TIL_DEN",
                 til_percentile=99.5,
                 til_bin_thr=0.1,
                 precomputed_scale=None,
                 transform=None):
        super().__init__()
        self.data_root      = Path(data_root)
        self.patients       = patient_list
        self.til_folder     = til_folder_name
        self.til_percentile = til_percentile
        self.til_bin_thr    = til_bin_thr
        self.transform      = transform

        self.samples = []   # list of (shg_path, til_path)

        for pid in self.patients:
            pdir    = self.data_root / pid
            shg_dir = pdir / "SHG"
            til_dir = pdir / self.til_folder

            if not shg_dir.exists():
                print(f"[WARN] No SHG dir for {pid}")
                continue
            if not til_dir.exists():
                print(f"[WARN] No TIL dir '{self.til_folder}' for {pid}")
                continue

            for shg_file in sorted(shg_dir.glob("*.png")):
                stem = shg_file.stem
                til_path = til_dir / f"{stem}.png"
                if til_path.exists():
                    self.samples.append((shg_file, til_path))
                else:
                    print(f"[WARN] Missing TIL for {shg_file.name} (expected {til_path.name})")

        if len(self.samples) == 0:
            raise RuntimeError(
                f"No SHG–TIL pairs found for patients {self.patients}. "
                f"Check folder names and file patterns."
            )

        # ----- global percentile scale for TIL density -----
        if precomputed_scale is None:
            print("Computing global TIL density percentile scale from PNGs...")
            all_vals = []
            for _, til_path in self.samples:
                til_img = Image.open(til_path).convert("F")
                den = np.array(til_img, dtype=np.float32) / 255.0  # [0,1]
                nz = den[den > 0]
                if nz.size > 0:
                    all_vals.append(nz)
            if len(all_vals) == 0:
                self.til_scale = 1.0
            else:
                all_vals = np.concatenate(all_vals)
                self.til_scale = np.percentile(all_vals, self.til_percentile) + 1e-6
            print(f"Global TIL scale (p{self.til_percentile}) = {self.til_scale:.4f}")
        else:
            self.til_scale = precomputed_scale

        # ----- patch-level stats for sampling -----
        self.patch_mass   = []
        self.is_pos_patch = []
        for _, til_path in self.samples:
            til_img = Image.open(til_path).convert("F")
            den = np.array(til_img, dtype=np.float32) / 255.0
            den_norm = np.clip(den / self.til_scale, 0.0, 1.0)
            self.patch_mass.append(float(den_norm.sum()))
            pos_pixels = (den_norm >= self.til_bin_thr).sum()
            self.is_pos_patch.append(pos_pixels >= MIN_POS_PIXELS)

        self.patch_mass   = np.array(self.patch_mass, dtype=np.float32)
        self.is_pos_patch = np.array(self.is_pos_patch, dtype=bool)

        # Print quick stats
        num_pos = int(self.is_pos_patch.sum())
        total   = len(self.is_pos_patch)
        print(f"[{','.join(self.patients)}] patches: {total}, "
              f"positive: {num_pos} ({100.0 * num_pos / total:.1f}%)")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        shg_path, til_path = self.samples[idx]

        # --- SHG image (input) ---
        shg_img = Image.open(shg_path).convert("L")
        img = np.array(shg_img, dtype=np.float32) / 255.0  # [0,1]

        # --- TIL density (continuous target) ---
        til_img = Image.open(til_path).convert("F")
        den = np.array(til_img, dtype=np.float32) / 255.0  # [0,1]

        den_norm = np.clip(den / self.til_scale, 0.0, 1.0)  # continuous target [0,1]

        img_hwc      = img[..., None]      # (H,W,1)
        den_cont_hwc = den_norm[..., None] # (H,W,1)

        if self.transform is not None:
            import albumentations as A
            from albumentations.pytorch import ToTensorV2

            # Use den_cont as mask so augmentations (flips/rotations) are aligned
            augmented = self.transform(image=img_hwc, mask=den_cont_hwc)
            img_t     = augmented["image"]     # (1,H,W)
            den_cont_t = augmented["mask"]     # (1,H,W), still continuous
        else:
            img_t      = torch.from_numpy(img_hwc.transpose(2,0,1)).float()
            den_cont_t = torch.from_numpy(den_cont_hwc.transpose(2,0,1)).float()

        return img_t, den_cont_t, idx


