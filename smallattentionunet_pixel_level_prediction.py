def structure_tensor_eigvals(Axx, Axy, Ayy):
    tmp  = 0.5 * (Axx + Ayy)
    diff = 0.5 * (Axx - Ayy)
    rad  = np.sqrt(diff**2 + Axy**2)
    l1 = tmp + rad
    l2 = tmp - rad
    return l1, l2

def structure_tensor_features(img):
    Axx, Axy, Ayy = structure_tensor(img, sigma=1)
    e1, e2 = structure_tensor_eigvals(Axx, Axy, Ayy)

    coherence = (e1 - e2) / (e1 + e2 + 1e-8)

    # Orientation angle
    theta = 0.5 * np.arctan2(2*Axy, Axx - Ayy)

    return {
        "coh_mean": coherence.mean(),
        "coh_std": coherence.std(),
        "ori_mean": np.mean(theta),
        "ori_std": np.std(theta),
    }

def gabor_energy(img, freq=0.2):
    feats = {}
    for theta in [0, np.pi/4, np.pi/2, 3*np.pi/4]:
        filt_real, filt_imag = gabor(img, frequency=freq, theta=theta)
        feats[f"gabor_{int(theta*180/np.pi)}"] = filt_real.mean()
    return feats

def fiber_skeleton_features(img):
    # Threshold using Otsu -> get fiber mask
    thr = cv2.threshold((img*255).astype(np.uint8), 0, 255, cv2.THRESH_OTSU)[1]
    mask = thr > 0

    skel = skeletonize(mask)

    # Get labeled skeleton components
    labeled = label(skel)
    props = regionprops(labeled)

    lengths = []
    straightness = []
    curvature_vals = []

    for p in props:
        coords = p.coords
        if len(coords) < 10:
            continue

        # length = number of pixels
        L = len(coords)
        lengths.append(L)

        # straightness = chord / arc length
        d = np.linalg.norm(coords[0] - coords[-1])
        straightness.append(d / (L + 1e-6))

        # curvature (approximate)
        diffs = np.diff(coords, axis=0)
        angles = np.arctan2(diffs[:,1], diffs[:,0])
        curvature = np.std(np.diff(angles))
        curvature_vals.append(curvature)

    if len(lengths)==0:
        return dict(fiber_len_mean=0, straight_mean=0, curv_mean=0)

    return {
        "fiber_len_mean": np.mean(lengths),
        "straight_mean": np.mean(straightness),
        "curv_mean": np.mean(curvature_vals),
    }

