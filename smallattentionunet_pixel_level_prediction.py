import torch
import torch.nn as nn
import torch.nn.functional as F

# -------- basic conv blocks --------
class DoubleConv(nn.Module):
    def __init__(self, in_ch, out_ch, dropout_p=0.0):
        super().__init__()
        self.seq = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False),
            nn.Conv2d(out_ch, out_ch, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False),
        )
        self.dropout = nn.Dropout2d(dropout_p) if dropout_p > 0 else nn.Identity()

    def forward(self, x):
        x = self.seq(x)
        x = self.dropout(x)
        return x

class Down(nn.Module):
    def __init__(self, in_ch, out_ch, dropout_p=0.0):
        super().__init__()
        self.pool = nn.MaxPool2d(2)
        self.conv = DoubleConv(in_ch, out_ch, dropout_p)

    def forward(self, x):
        x = self.pool(x)
        x = self.conv(x)
        return x

# -------- attention gate --------
class AttentionGate(nn.Module):
    def __init__(self, F_g, F_l, F_int):
        """
        F_g: channels of gating signal (from decoder)
        F_l: channels of skip connection (from encoder)
        F_int: intermediate channels
        """
        super().__init__()
        self.W_g = nn.Sequential(
            nn.Conv2d(F_g, F_int, kernel_size=1, bias=True),
            nn.BatchNorm2d(F_int),
        )
        self.W_x = nn.Sequential(
            nn.Conv2d(F_l, F_int, kernel_size=1, bias=True),
            nn.BatchNorm2d(F_int),
        )
        self.psi = nn.Sequential(
            nn.Conv2d(F_int, 1, kernel_size=1, bias=True),
            nn.BatchNorm2d(1),
            nn.Sigmoid()
        )
        self.relu = nn.ReLU(inplace=False)

    def forward(self, x, g):
        # x: encoder skip, g: decoder feature
        g1 = self.W_g(g)
        x1 = self.W_x(x)

        # upsample smaller one if shapes mismatch
        if g1.shape[-2:] != x1.shape[-2:]:
            g1 = F.interpolate(g1, size=x1.shape[-2:], mode="bilinear", align_corners=False)

        psi = self.relu(g1 + x1)
        psi = self.psi(psi)      # [B,1,H,W]
        out = x * psi            # apply attention
        return out

class UpAttn(nn.Module):
    def __init__(self, in_ch, skip_ch, out_ch, dropout_p=0.0):
        """
        in_ch:   decoder feature channels
        skip_ch: encoder skip channels
        out_ch:  output channels after fusion
        """
        super().__init__()
        self.up   = nn.ConvTranspose2d(in_ch, in_ch // 2, kernel_size=2, stride=2)
        self.attn = AttentionGate(F_g=in_ch // 2, F_l=skip_ch, F_int=skip_ch // 2)
        self.conv = DoubleConv(in_ch // 2 + skip_ch, out_ch, dropout_p)

    def forward(self, x, skip):
        x = self.up(x)
        if x.shape[-2:] != skip.shape[-2:]:
            x = F.interpolate(x, size=skip.shape[-2:], mode="bilinear", align_corners=False)

        skip_attn = self.attn(skip, x)
        x = torch.cat([skip_attn, x], dim=1)
        x = self.conv(x)
        return x

class AttnUNet(nn.Module):
    def __init__(self, in_ch=1, out_ch=1, base_ch=32, dropout_p=0.2):
        """
        in_ch:   4 for HE+SHG (RGB+SHG)
        out_ch:  1 for TIL density map
        base_ch: width of the first layer (scales as 32,64,128,256,512)
        """
        super().__init__()
        self.inc   = DoubleConv(in_ch,      base_ch,     dropout_p)
        self.down1 = Down(base_ch,          base_ch*2,   dropout_p)
        self.down2 = Down(base_ch*2,        base_ch*4,   dropout_p)
        self.down3 = Down(base_ch*4,        base_ch*8,   dropout_p)
        self.down4 = Down(base_ch*8,        base_ch*16,  dropout_p)

        self.up1   = UpAttn(base_ch*16,     base_ch*8,   base_ch*8,  dropout_p)
        self.up2   = UpAttn(base_ch*8,      base_ch*4,   base_ch*4,  dropout_p)
        self.up3   = UpAttn(base_ch*4,      base_ch*2,   base_ch*2,  dropout_p)
        self.up4   = UpAttn(base_ch*2,      base_ch,     base_ch,    dropout_p)

        self.outc  = nn.Conv2d(base_ch, out_ch, kernel_size=1)

    def forward(self, x):
        x1 = self.inc(x)     # [B, base,   H,   W]
        x2 = self.down1(x1)  # [B, 2base,  H/2, W/2]
        x3 = self.down2(x2)  # [B, 4base,  H/4, W/4]
        x4 = self.down3(x3)  # [B, 8base,  H/8, W/8]
        x5 = self.down4(x4)  # [B,16base, H/16,W/16]

        x  = self.up1(x5, x4)
        x  = self.up2(x,  x3)
        x  = self.up3(x,  x2)
        x  = self.up4(x,  x1)

        logits = self.outc(x)  # [B,1,H,W]
        return logits



