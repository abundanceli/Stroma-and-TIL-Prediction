def occlusion_explainer(model, x, patch=64, stride=64):
    """
    x: (1,C,H,W) on CUDA
    Returns attribution map: (C,H,W)
    """

    assert x.is_cuda, "Input x must be moved to CUDA!"
    model.eval()

    _, C, H, W = x.shape

    attr = torch.zeros((C, H, W), device=x.device)

    # baseline prediction
    with torch.no_grad():
        baseline = model(x)[0,0].detach()

    # occlusion loop
    for y in range(0, H, stride):
        for z in range(0, W, stride):

            # copy X
            x_occ = x.clone()

            # apply occlusion (zero-out)
            y2 = min(y + patch, H)
            z2 = min(z + patch, W)
            x_occ[:,:, y:y2, z:z2] = 0.0

            with torch.no_grad():
                out_occ = model(x_occ)[0,0]

            diff = (baseline - out_occ).abs()

            # store difference in attribution map
            attr[:, y:y2, z:z2] += diff[y:y2, z:z2]

    # normalize attribution
    attr = (attr - attr.min()) / (attr.max() + 1e-8)

    return attr

