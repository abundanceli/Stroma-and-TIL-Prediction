def run_with_attention(model, ds, idx):
    """
    Run model on a single sample from dataset ds[idx]
    and return SHG, GT TIL, Pred TIL, and attention maps from each gate.
    """
    model.eval()
    img_t, den_cont_t, _ = ds[idx]

    # fix target shape if needed, but mostly we care about img here
    if den_cont_t.ndim == 3 and den_cont_t.shape[0] != 1 and den_cont_t.shape[-1] == 1:
        den_cont_t = den_cont_t.permute(2, 0, 1)

    img = img_t.unsqueeze(0).to(DEVICE)          # [1,1,H,W]
    den_cont = den_cont_t.unsqueeze(0).to(DEVICE)

    with torch.no_grad():
        with torch.amp.autocast(device_type='cuda', enabled=(DEVICE.type == "cuda")):
            logits = model(img)
            probs  = torch.sigmoid(logits)

    # base maps for plotting
    shg_np  = img_t[0].cpu().numpy()
    gt_np   = den_cont_t[0].cpu().numpy()
    pred_np = probs[0, 0].cpu().numpy()

    H, W = shg_np.shape

    # collect attention maps from each gate (if present)
    att_maps = []
    att_names = []

    # adjust these names if your model uses different attribute names
    gates = [
        ("up1", getattr(model, "up1", None)),
        ("up2", getattr(model, "up2", None)),
        ("up3", getattr(model, "up3", None)),
        ("up4", getattr(model, "up4", None)),
    ]

    for name, up_block in gates:
        if up_block is None:
            continue
        gate = getattr(up_block, "att", None)
        if gate is None or gate.last_psi is None:
            continue

        psi = gate.last_psi[0, 0]          # [h,w]
        psi_up = F.interpolate(
            gate.last_psi, size=(H, W), mode="bilinear", align_corners=False
        )[0, 0].cpu().numpy()              # upsample to input size

        att_maps.append(psi_up)
        att_names.append(name)

    return shg_np, gt_np, pred_np, att_maps, att_names

