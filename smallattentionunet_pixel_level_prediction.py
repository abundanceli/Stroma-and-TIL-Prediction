def compute_mild_balance_weights(train_ds, test_ds=None, target_pos_rate=None, save_fig=True):
    """
    Mild, stable patch-level reweighting:
      - we ONLY use the binary label is_pos_patch
      - we compute a global positive scaling factor s_pos that
        moves the effective positive rate from r -> target t
      - weights are soft (no hard dropping), used in WeightedRandomSampler
    """

    y = train_ds.is_pos_patch.astype(int)
    cur_pos_rate = float(y.mean())

    if test_ds is not None:
        test_pos_rate = float(test_ds.is_pos_patch.mean())
    else:
        test_pos_rate = None

    # ---- choose a mild target ----
    if target_pos_rate is None:
        if test_pos_rate is not None:
            # mild: halfway between train and test
            target_pos_rate = 0.5 * cur_pos_rate + 0.5 * test_pos_rate
        else:
            # fallback: move 25% of the way toward 0.5
            target_pos_rate = 0.75 * cur_pos_rate + 0.25 * 0.5

    t = float(target_pos_rate)
    r = cur_pos_rate

    # clamp so we don't try anything crazy
    t = max(0.05, min(0.95, t))

    print(f"Current train positive rate   : {r:.3f}")
    if test_pos_rate is not None:
        print(f"Test positive rate            : {test_pos_rate:.3f}")
    print(f"Mild target train pos. rate   : {t:.3f}")

    # ---- solve for positive scaling factor s_pos ----
    # If we set w_pos = s_pos, w_neg = 1,
    # weighted positive fraction is:
    #   f = s_pos * r / (s_pos * r + (1 - r))
    # Solve for s_pos such that f = t:
    #   s_pos * r / (s_pos * r + 1 - r) = t
    #   => s_pos = t(1 - r) / [ r (1 - t) ]
    eps = 1e-6
    s_pos = t * (1.0 - r) / (r * (1.0 - t) + eps)

    print(f"Positive weight scale s_pos   : {s_pos:.3f}")

    # ---- build weights ----
    w = np.where(y == 1, s_pos, 1.0).astype(np.float32)

    # normalize so mean weight ~1 (helps sampler)
    w = w / w.mean()

    # compute achieved weighted rate
    weighted_pos_rate = float(np.average(y, weights=w))
    print(f"Weighted train positive rate  : {weighted_pos_rate:.3f}")

    # ---- paper-ready visualization ----
    if save_fig:
        fig, axes = plt.subplots(1, 2, figsize=(11, 4))

        # panel 1: positive fraction bar plot
        names = ["Train (raw)", "Train (mild-bal.)", "Test"]
        vals  = [r, weighted_pos_rate,
                 test_pos_rate if test_pos_rate is not None else np.nan]
        colors = ["tab:blue", "tab:orange", "tab:green"]

        axes[0].bar(names, vals, color=colors)
        axes[0].set_ylim(0, 1)
        axes[0].set_ylabel("Positive patch fraction")
        axes[0].set_title("Positive rate before/after mild reweighting")

        # panel 2: TIL mass histograms (for context, same as before)
        til_train = np.asarray(train_ds.patch_mass, dtype=np.float32)
        if test_ds is not None:
            til_test = np.asarray(test_ds.patch_mass, dtype=np.float32)
        else:
            til_test = None

        til_train_log = np.log1p(til_train)
        if test_ds is not None:
            til_test_log = np.log1p(til_test)

        bins = 40
        axes[1].hist(
            til_train_log,
            bins=bins,
            alpha=0.5,
            label=f"Train (raw, n={len(til_train)})",
            density=True,
        )
        axes[1].hist(
            til_train_log,
            bins=bins,
            weights=w / w.mean(),
            alpha=0.5,
            label="Train (mild-bal.)",
            density=True,
        )
        if test_ds is not None:
            axes[1].hist(
                til_test_log,
                bins=bins,
                alpha=0.5,
                label=f"Test (n={len(til_test)})",
                density=True,
            )

        axes[1].set_xlabel("log(1 + patch TIL mass)")
        axes[1].set_ylabel("Density")
        axes[1].set_title("Patch-level TIL distribution: raw vs mild-bal. vs test")
        axes[1].legend(frameon=False)

        plt.tight_layout()
        fig_path = OUT_DIR / "mild_balance.png"
        plt.savefig(fig_path, dpi=300, bbox_inches="tight")
        print(f"Mild balance figure saved to: {fig_path}")

    return w




