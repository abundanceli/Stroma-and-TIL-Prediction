def read_gray(path: Path):
    img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise IOError(f"Could not read image: {path}")
    return img

# --- Helper for robust min-max normalization ---
def robust_minmax(x, low_pct=1.0, high_pct=99.0):
    """
    Clip to [low_pct, high_pct] percentiles and min-max normalize to [0,1].
    Helps avoid a few super-bright pixels dominating the dynamic range.
    """
    x = x.astype(np.float32)
    lo, hi = np.percentile(x, [low_pct, high_pct])
    if hi <= lo:
        return np.zeros_like(x, dtype=np.float32)

    x = (x - lo) / (hi - lo)
    return x

