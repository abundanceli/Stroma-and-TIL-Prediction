def channel_occlusion(model, x):
    model.eval()
    base_pred = model(x).detach()

    results = {}
    for ch in range(x.shape[1]):
        x_occ = x.clone()
        x_occ[:, ch] = 0.0   # remove channel
        pred_occ = model(x_occ).detach()
        diff = (base_pred - pred_occ).abs().mean().item()
        results[f"channel_{ch}"] = diff
    return results

