def train_one_epoch(model, loader, optimizer, scaler, criterion):
    model.train()
    running_loss = 0.0

    def _fix_target_shape(den_cont):
    # we want [B, 1, H, W]
        if den_cont.ndim == 4:
            # case like [B, H, W, 1]
            if den_cont.shape[1] != 1 and den_cont.shape[-1] == 1:
                den_cont = den_cont.permute(0, 3, 1, 2).contiguous()
        return den_cont


    for imgs, den_cont, _ in loader:
        imgs     = imgs.to(DEVICE, non_blocking=True)
        den_cont = den_cont.to(DEVICE, non_blocking=True)
        den_cont = _fix_target_shape(den_cont)      # <--- add this line

        optimizer.zero_grad()
        with torch.amp.autocast(device_type='cuda', enabled=(DEVICE.type == "cuda")):
            logits = model(imgs)                    # [B,1,512,512]
            loss   = criterion(logits, den_cont)    # shapes now match


        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        running_loss += loss.item() * imgs.size(0)

    epoch_loss = running_loss / len(loader.dataset)
    return epoch_loss


def eval_model(model, loader, criterion):
    model.eval()
    running_loss = 0.0
    aurocs, auprcs = [], []

    def _fix_target_shape(den_cont):
    # we want [B, 1, H, W]
        if den_cont.ndim == 4:
            # case like [B, H, W, 1]
            if den_cont.shape[1] != 1 and den_cont.shape[-1] == 1:
                den_cont = den_cont.permute(0, 3, 1, 2).contiguous()
        return den_cont


    with torch.no_grad():
        for imgs, den_cont, _ in loader:
            imgs     = imgs.to(DEVICE, non_blocking=True)
            den_cont = den_cont.to(DEVICE, non_blocking=True)
            den_cont = _fix_target_shape(den_cont)      # <--- same fix

            with torch.amp.autocast(device_type='cuda', enabled=(DEVICE.type == "cuda")):
                logits = model(imgs)
                loss   = criterion(logits, den_cont)


            running_loss += loss.item() * imgs.size(0)

            a, p = compute_pixel_metrics(logits, den_cont)
            if not np.isnan(a):
                aurocs.append(a)
            if not np.isnan(p):
                auprcs.append(p)

    mean_loss  = running_loss / len(loader.dataset)
    mean_auroc = float(np.mean(aurocs)) if len(aurocs) > 0 else np.nan
    mean_auprc = float(np.mean(auprcs)) if len(auprcs) > 0 else np.nan
    return mean_loss, mean_auroc, mean_auprc


