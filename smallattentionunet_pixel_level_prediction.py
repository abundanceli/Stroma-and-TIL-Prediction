def get_fold_splits(fold_idx: int):
    """
    3 folds, each with:
      N_train = total - 4
      N_val   = 2
      N_test  = 2
    Patients are taken from PATIENT_CODES (sorted).
    """
    assert 0 <= fold_idx < 3

    N_PATIENTS = len(PATIENT_CODES)
    base = (3 * fold_idx) % N_PATIENTS

    test_indices = [
        base % N_PATIENTS,
        (base + 1) % N_PATIENTS
    ]
    val_indices = [
        (base + 2) % N_PATIENTS,
        (base + 3) % N_PATIENTS
    ]

    test_patients = [PATIENT_CODES[i] for i in test_indices]
    val_patients  = [PATIENT_CODES[i] for i in val_indices]

    test_set = set(test_patients)
    val_set  = set(val_patients)

    train_patients = [p for p in PATIENT_CODES if p not in test_set and p not in val_set]

    assert len(val_patients) == 2
    assert len(test_patients) == 2
    assert len(train_patients) == N_PATIENTS - 4

    print(f"\n===== Fold {fold_idx} =====")
    print("  Train patients:", train_patients)
    print("  Val patients:  ", val_patients)
    print("  Test patients: ", test_patients)

    return train_patients, val_patients, test_patients


