@torch.no_grad()
def collect_predictions_and_til(model, loader, device):
    """
    Collect:
      - flattened scores (probs in [0,1])
      - flattened binary labels (target>0)
      - per-patient true/predicted %TIL
      - global true/pred %TIL
    """
    model.eval()

    all_scores = []
    all_labels = []

    patient_true_sum  = defaultdict(float)
    patient_pred_sum  = defaultdict(float)
    patient_pixel_cnt = defaultdict(int)

    total_true_sum = 0.0
    total_pred_sum = 0.0
    total_pixels   = 0

    for xb, yb, meta in tqdm(loader, desc="[collect preds]"):
        xb = xb.to(device, non_blocking=True)
        yb = yb.to(device, non_blocking=True)

        logits = model(xb)
        probs  = torch.sigmoid(logits)  # [B,1,H,W]

        scores = probs.detach().cpu().numpy().ravel()
        labels = (yb.detach().cpu().numpy() > 0.0).astype(np.uint8).ravel()

        all_scores.append(scores)
        all_labels.append(labels)

        if isinstance(meta, dict):
            patients = meta["patient"]
        else:
            patients = [m["patient"] for m in meta]

        B = xb.size(0)
        for i in range(B):
            pt = patients[i]
            y_i = yb[i, 0]
            p_i = probs[i, 0]

            patient_true_sum[pt]  += float(y_i.sum().item())
            patient_pred_sum[pt]  += float(p_i.sum().item())
            patient_pixel_cnt[pt] += int(y_i.numel())

            total_true_sum += float(y_i.sum().item())
            total_pred_sum += float(p_i.sum().item())
            total_pixels   += int(y_i.numel())

    all_scores = np.concatenate(all_scores)
    all_labels = np.concatenate(all_labels)

    patient_til_pct = {}
    for pt in sorted(patient_pixel_cnt.keys()):
        npx = patient_pixel_cnt[pt]
        true_pct = 100.0 * patient_true_sum[pt] / max(1, npx)
        pred_pct = 100.0 * patient_pred_sum[pt] / max(1, npx)
        patient_til_pct[pt] = {"true_pct": true_pct, "pred_pct": pred_pct}

    global_true_pct = 100.0 * total_true_sum / max(1, total_pixels)
    global_pred_pct = 100.0 * total_pred_sum / max(1, total_pixels)

    return all_scores, all_labels, patient_til_pct, global_true_pct, global_pred_pct


def plot_roc_pr_confusion(scores, labels, title_prefix="TEST"):
    """
    Plot ROC, PR, and confusion matrix (at F1-optimal threshold)
    Return best_thr, auroc, auprc.
    """
    # ROC
    fpr, tpr, roc_thr = roc_curve(labels, scores)
    auroc = roc_auc_score(labels, scores)

    # PR
    precision, recall, pr_thr = precision_recall_curve(labels, scores)
    auprc = average_precision_score(labels, scores)

    print(f"{title_prefix} AUROC = {auroc:.4f}, AUPRC = {auprc:.4f}")

    plt.figure(figsize=(12, 4))

    # ROC curve
    plt.subplot(1, 3, 1)
    plt.plot(fpr, tpr)
    plt.plot([0, 1], [0, 1], "--")
    plt.xlabel("False Positive Rate")
    plt.ylabel("True Positive Rate")
    plt.title(f"{title_prefix} ROC (AUROC={auroc:.3f})")

    # PR curve
    plt.subplot(1, 3, 2)
    plt.plot(recall, precision)
    plt.xlabel("Recall")
    plt.ylabel("Precision")
    plt.title(f"{title_prefix} PR (AUPRC={auprc:.3f})")

    # F1-opt threshold from PR curve
    # last point of PR curve has no threshold
    f1 = 2 * precision[:-1] * recall[:-1] / (precision[:-1] + recall[:-1] + 1e-8)
    best_idx = int(np.argmax(f1))
    best_thr = float(pr_thr[best_idx])
    print(
        f"{title_prefix} F1-optimal threshold = {best_thr:.4f} "
        f"(P={precision[best_idx]:.3f}, R={recall[best_idx]:.3f})"
    )

    # Confusion matrix at F1-opt threshold
    preds_bin = (scores >= best_thr).astype(int)
    cm = confusion_matrix(labels, preds_bin)

    plt.subplot(1, 3, 3)
    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cbar=False,
        xticklabels=["Pred 0", "Pred 1"],
        yticklabels=["True 0", "True 1"],
    )
    plt.title("Confusion matrix")
    plt.tight_layout()
    plt.show()

    return best_thr, auroc, auprc


