def compute_fiber_coherence(shg_img, mask=None, sigma=2.0):
    """
    shg_img: 2D numpy array, assumed already normalized (0–1)
    mask   : 2D boolean or 0/1 array; if provided, coherence is averaged over mask region
    """
    img = shg_img.astype(np.float32)
    Axx, Axy, Ayy = structure_tensor(img, sigma=sigma)

    # Manually calculate eigenvalues from structure tensor components
    # Source: https://scikit-image.org/docs/stable/api/skimage.feature.html#skimage.feature.structure_tensor_eigvals
    # l1, l2 = structure_tensor_eigvals(Axx, Axy, Ayy) # This function is not found

    tmp = np.sqrt((Axx - Ayy)**2 + 4 * Axy**2)
    l1 = 0.5 * (Axx + Ayy + tmp)
    l2 = 0.5 * (Axx + Ayy - tmp)

    # Avoid division by zero where l1 + l2 is zero
    divisor = l1 + l2 + 1e-8
    coherence = (l1 - l2) / divisor   # 0 = isotropic, 1 = highly aligned

    if mask is not None:
        m = mask.astype(bool)
        vals = coherence[m]
    else:
        vals = coherence.ravel()

    return float(vals.mean()) if vals.size > 0 else np.nan

